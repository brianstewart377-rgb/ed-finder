CREATE TABLE v3_private.private_import (
    private_import_id uuid PRIMARY KEY,
    owner_account_id uuid NOT NULL REFERENCES v3_identity.account(account_id),
    owner_commander_id uuid,
    source_run_id uuid NOT NULL REFERENCES v3_source.source_run(source_run_id),
