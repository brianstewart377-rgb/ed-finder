CREATE TABLE v3_identity.session (
    session_id uuid PRIMARY KEY,
    account_id uuid NOT NULL REFERENCES v3_identity.account(account_id),
    device_credential_id uuid REFERENCES v3_identity.device_credential(device_credential_id),
    session_token_sha256 bytea NOT NULL UNIQUE,
    session_state text NOT NULL DEFAULT 'ACTIVE' CHECK (session_state IN (
        'ACTIVE', 'ROTATED', 'REVOKED'
    )),
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    last_seen_at timestamptz NOT NULL,
    idle_expires_at timestamptz NOT NULL,
    absolute_expires_at timestamptz NOT NULL,
    last_authenticated_at timestamptz NOT NULL,
    recent_auth_expires_at timestamptz NOT NULL,
    rotation_counter bigint NOT NULL DEFAULT 0 CHECK (rotation_counter >= 0),
    rotated_to_session_id uuid,
    rotated_at timestamptz,
    revoked_at timestamptz,
    UNIQUE (session_id, account_id),
    FOREIGN KEY (rotated_to_session_id, account_id)
        REFERENCES v3_identity.session(session_id, account_id),
    CHECK (octet_length(session_token_sha256) = 32),
    CHECK (last_seen_at >= created_at),
    CHECK (idle_expires_at > last_seen_at),
    CHECK (absolute_expires_at > created_at),
    CHECK (idle_expires_at <= absolute_expires_at),
    CHECK (last_authenticated_at >= created_at),
    CHECK (recent_auth_expires_at > last_authenticated_at),
    CHECK (recent_auth_expires_at <= absolute_expires_at),
    CHECK ((session_state = 'ROTATED') =
        (rotated_to_session_id IS NOT NULL AND rotated_at IS NOT NULL)),
    CHECK ((session_state = 'REVOKED') = (revoked_at IS NOT NULL)),
    CHECK (rotated_at IS NULL OR rotated_at >= created_at),
    CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

CREATE INDEX session_account_active_idx
    ON v3_identity.session(account_id, idle_expires_at, absolute_expires_at)
    WHERE session_state = 'ACTIVE';
COMMENT ON INDEX v3_identity.session_account_active_idx IS 'Use: authorize active sessions against both idle and absolute expiry.';

