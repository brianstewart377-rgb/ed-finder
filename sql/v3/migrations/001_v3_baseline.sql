CREATE FUNCTION v3_meta.is_percentage_object(value jsonb, is_complete boolean)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
RETURNS NULL ON NULL INPUT
AS $function$
    WITH entries AS MATERIALIZED (
        SELECT entry.value
        FROM jsonb_each(
            CASE
                WHEN jsonb_typeof(value) = 'object' THEN value
                ELSE '{}'::jsonb
            END
        ) AS entry
    ), summary AS (
        SELECT
            count(*) AS entry_count,
            count(*) FILTER (WHERE jsonb_typeof(entries.value) = 'number') AS numeric_count,
            sum((entries.value #>> '{}')::numeric)
                FILTER (WHERE jsonb_typeof(entries.value) = 'number') AS total,
            bool_and(
                CASE
                    WHEN jsonb_typeof(entries.value) = 'number'
                    THEN (entries.value #>> '{}')::numeric BETWEEN 0 AND 100
                    ELSE false
                END
            ) AS values_in_range
        FROM entries
    )
    SELECT
        jsonb_typeof(value) = 'object'
        AND entry_count > 0
        AND numeric_count = entry_count
        AND values_in_range
        AND (NOT is_complete OR abs(total - 100) <= 0.0001)
    FROM summary;
$function$;

COMMENT ON FUNCTION v3_meta.is_percentage_object(jsonb, boolean) IS 'Validates non-empty percentage maps with individual values in [0,100]; complete maps sum to 100 while incomplete source maps retain their raw total without treating omitted keys as zero.';

