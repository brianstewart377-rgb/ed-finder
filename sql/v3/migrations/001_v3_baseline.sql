CREATE TABLE v3_private.private_fact (
    private_fact_id uuid PRIMARY KEY,
    private_import_id uuid NOT NULL,
    owner_account_id uuid NOT NULL,
    source_run_id uuid NOT NULL REFERENCES v3_source.source_run(source_run_id),
    fact_kind text NOT NULL,
    fact_key jsonb NOT NULL,
    fact_payload jsonb NOT NULL,
    observed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
