CREATE FUNCTION v3_meta.publish_canonical_generation(
    target_generation_id uuid,
    publication_reason text,
    publication_actor text
)
RETURNS bigint
LANGUAGE plpgsql
AS $function$
DECLARE
    prior_generation_id uuid;
    next_sequence bigint;
    target_state text;
    target_validated_at timestamptz;
    target_schema text;
    physical_relation_count integer;
BEGIN
    IF publication_reason IS NULL OR btrim(publication_reason) = '' THEN
        RAISE EXCEPTION 'publication reason is required';
    END IF;
    IF publication_actor IS NULL OR btrim(publication_actor) = '' THEN
        RAISE EXCEPTION 'publication actor is required';
    END IF;

    PERFORM pg_advisory_xact_lock(hashtextextended('edfinder-v3-canonical-publication', 0));

    SELECT lifecycle_state, validation_completed_at, relation_schema
      INTO target_state, target_validated_at, target_schema
      FROM v3_meta.canonical_generation
     WHERE generation_id = target_generation_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'unknown canonical generation %', target_generation_id;
    END IF;
    IF target_state NOT IN ('READY', 'PUBLISHED', 'RETIRED') OR target_validated_at IS NULL THEN
        RAISE EXCEPTION 'generation % is not validated and publishable', target_generation_id;
    END IF;

    SELECT count(*)
      INTO physical_relation_count
      FROM pg_class relation
      JOIN pg_namespace namespace ON namespace.oid = relation.relnamespace
     WHERE namespace.nspname = target_schema
       AND relation.relkind = 'r'
       AND relation.relname = ANY (ARRAY[
            'systems', 'bodies', 'body_composition', 'body_alias',
            'body_parent_evidence', 'rings', 'body_signal_current',
            'body_genus_current', 'ring_signal_current', 'stations',
            'station_alias', 'station_placement', 'station_service_current',
            'station_economy_current'
       ]);
    IF physical_relation_count <> 14 THEN
        RAISE EXCEPTION USING
            ERRCODE = '55000',
            MESSAGE = format(
                'generation %s physical schema %s is missing or incomplete',
                target_generation_id, target_schema
            );
    END IF;

    SELECT generation_id, publication_sequence
      INTO prior_generation_id, next_sequence
      FROM v3_meta.current_canonical_generation
     WHERE singleton
     FOR UPDATE;

    IF prior_generation_id = target_generation_id THEN
        RETURN next_sequence;
    END IF;

    next_sequence := COALESCE(next_sequence, 0) + 1;

    IF prior_generation_id IS NOT NULL THEN
        UPDATE v3_meta.canonical_generation
           SET lifecycle_state = 'RETIRED', retired_at = transaction_timestamp()
         WHERE generation_id = prior_generation_id;
    END IF;

    UPDATE v3_meta.canonical_generation
       SET lifecycle_state = 'PUBLISHED',
           published_at = COALESCE(published_at, transaction_timestamp()),
           retired_at = NULL
     WHERE generation_id = target_generation_id;

    INSERT INTO v3_meta.current_canonical_generation(
        singleton, generation_id, publication_sequence, published_at
    ) VALUES (
        true, target_generation_id, next_sequence, transaction_timestamp()
    )
    ON CONFLICT (singleton) DO UPDATE
       SET generation_id = EXCLUDED.generation_id,
           publication_sequence = EXCLUDED.publication_sequence,
           published_at = EXCLUDED.published_at;

    INSERT INTO v3_meta.canonical_publication_audit(
        publication_sequence, from_generation_id, to_generation_id,
        published_at, published_by, transaction_id, reason
    ) VALUES (
        next_sequence, prior_generation_id, target_generation_id,
        transaction_timestamp(), publication_actor, txid_current(), publication_reason
    );

    RETURN next_sequence;
END;
$function$;

COMMENT ON FUNCTION v3_meta.publish_canonical_generation(uuid, text, text) IS 'Transactional generation pointer publication/rollback. Candidate read relations must already be READY; no view DDL occurs.';

COMMIT;
