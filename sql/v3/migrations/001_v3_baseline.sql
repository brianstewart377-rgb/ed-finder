    SELECT relation_schema, lifecycle_state
      INTO target_schema, target_state
      FROM v3_meta.canonical_generation
     WHERE generation_id = target_generation_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'unknown canonical generation %', target_generation_id;
    END IF;
    IF target_state <> 'BUILDING' THEN
        RAISE EXCEPTION 'generation % is %, expected BUILDING', target_generation_id, target_state;
    END IF;
    IF receipt IS NULL OR jsonb_typeof(receipt) <> 'object' THEN
        RAISE EXCEPTION 'validation receipt must be a JSON object';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = target_schema) THEN
        RAISE EXCEPTION 'generation schema % is missing', target_schema;
    END IF;
    IF NOT EXISTS (
        SELECT 1
          FROM v3_meta.canonical_generation_input
         WHERE generation_id = target_generation_id
    ) THEN
        RAISE EXCEPTION 'generation % has no input manifest', target_generation_id;
    END IF;
    IF NOT EXISTS (
        SELECT 1
          FROM v3_meta.canonical_generation generation
          JOIN v3_meta.canonical_generation_input input
            ON input.generation_id = generation.generation_id
           AND input.source_run_id = generation.build_source_run_id
         WHERE generation.generation_id = target_generation_id
    ) THEN
        RAISE EXCEPTION 'generation % build coordinator run is absent from its input manifest',
            target_generation_id;
