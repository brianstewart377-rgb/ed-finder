                    UNION SELECT source_run_id FROM %1$I.body_parent_evidence
                    UNION SELECT source_run_id FROM %1$I.rings
                    UNION SELECT last_present_run_id FROM %1$I.rings
                    UNION SELECT first_missing_run_id FROM %1$I.rings
                    UNION SELECT last_missing_run_id FROM %1$I.rings
