CREATE FUNCTION v3_async.enforce_job_chunk_completion_fence()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    IF TG_OP = 'UPDATE'
       AND OLD.chunk_state IN ('SUCCEEDED', 'FAILED', 'QUARANTINED') THEN
        IF NEW.chunk_state IS NOT DISTINCT FROM OLD.chunk_state
           AND NEW.attempt_number IS NOT DISTINCT FROM OLD.attempt_number
           AND NEW.fencing_token IS NOT DISTINCT FROM OLD.fencing_token
           AND NEW.output_sha256 IS NOT DISTINCT FROM OLD.output_sha256
           AND NEW.started_at IS NOT DISTINCT FROM OLD.started_at
           AND NEW.completed_at IS NOT DISTINCT FROM OLD.completed_at
           AND NEW.rows_read IS NOT DISTINCT FROM OLD.rows_read
           AND NEW.rows_written IS NOT DISTINCT FROM OLD.rows_written
           AND NEW.rows_rejected IS NOT DISTINCT FROM OLD.rows_rejected THEN
            -- Deliberately permit an exact idempotent/no-op retry only.
            RETURN NEW;
        END IF;

        RAISE EXCEPTION USING
            ERRCODE = '55000',
            MESSAGE = format(
                'terminal completion metadata is immutable for job %s chunk %s',
                NEW.job_id, NEW.chunk_key
            );
    END IF;

    IF NEW.chunk_state IN ('SUCCEEDED', 'FAILED', 'QUARANTINED')
       AND (TG_OP = 'INSERT' OR
            OLD.chunk_state NOT IN ('SUCCEEDED', 'FAILED', 'QUARANTINED')) THEN
        PERFORM 1
          FROM v3_async.job_lease lease
          JOIN v3_async.job job ON job.job_id = lease.job_id
         WHERE lease.job_id = NEW.job_id
           AND lease.fencing_token = NEW.fencing_token
           AND lease.acquired_at <= clock_timestamp()
           AND lease.expires_at > clock_timestamp()
           AND job.job_state = 'RUNNING'
         FOR UPDATE OF lease;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING
                ERRCODE = '55000',
                MESSAGE = format(
                    'stale, unknown, or expired completion fence for job %s token %s',
                    NEW.job_id, NEW.fencing_token
                );
        END IF;

        PERFORM 1
          FROM v3_async.job_attempt
         WHERE job_id = NEW.job_id
           AND attempt_number = NEW.attempt_number
           AND fencing_token = NEW.fencing_token
           AND attempt_state = 'RUNNING';
        IF NOT FOUND THEN
            RAISE EXCEPTION USING
                ERRCODE = '55000',
                MESSAGE = format(
                    'unknown or inactive completion attempt for job %s attempt %s token %s',
                    NEW.job_id, NEW.attempt_number, NEW.fencing_token
                );
        END IF;
    END IF;
    RETURN NEW;
END;
$function$;

CREATE TRIGGER job_chunk_completion_fence_trigger
BEFORE INSERT OR UPDATE OF
    chunk_state, attempt_number, fencing_token, output_sha256,
    started_at, completed_at, rows_read, rows_written, rows_rejected
ON v3_async.job_chunk
FOR EACH ROW EXECUTE FUNCTION v3_async.enforce_job_chunk_completion_fence();

