-- ED-Finder V3 migration 001: fresh PostgreSQL 18 baseline.
-- PRODUCTION-INTENDED SCHEMA SOURCE — NOT YET DEPLOYED.
--
-- This migration intentionally has no dependency on the V2 migration chain.
-- Required PostgreSQL extensions: none. In particular, PostGIS is not used.

BEGIN;

CREATE SCHEMA v3_source;
CREATE SCHEMA v3_vocab;
CREATE SCHEMA v3_identity;
CREATE SCHEMA v3_private;
CREATE SCHEMA v3_meta;
CREATE SCHEMA v3_async;

COMMENT ON SCHEMA v3_source IS 'V3 source acquisition, provenance, reconciliation evidence, and unmapped source vocabulary.';
COMMENT ON SCHEMA v3_vocab IS 'V3 governed public vocabulary. Internal smallint tokens are never public identity.';
COMMENT ON SCHEMA v3_identity IS 'V3 product accounts, Commanders, credentials, roles, and provider-scoped identities.';
COMMENT ON SCHEMA v3_private IS 'V3 private trust-zone imports/facts and explicit contribution/withdrawal receipts.';
COMMENT ON SCHEMA v3_meta IS 'V3 migration, canonical generation, relation-build, validation, and publication metadata.';
COMMENT ON SCHEMA v3_async IS 'V3 authoritative durable jobs, leases, attempts, chunks, outbox, and effect receipts.';

-- ---------------------------------------------------------------------------
-- Source/acquisition ledger (ADR-007, ADR-010, ADR-017)
-- ---------------------------------------------------------------------------

CREATE TABLE v3_source.source (
    source_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code text NOT NULL UNIQUE,
    display_name text NOT NULL,
    endpoint_identity text,
    authority_class text NOT NULL CHECK (authority_class IN (
        'OPERATOR_ADJUDICATION', 'FRONTIER_DIRECT', 'PRIMARY_AGGREGATED',
        'SECONDARY_AGGREGATED', 'REFERENCE_CURATED', 'LEGACY_FALLBACK'
    )),
    enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    CHECK (source_code ~ '^[a-z][a-z0-9_.-]{0,62}$')
);

COMMENT ON TABLE v3_source.source IS 'Source/endpoint identity only. Credentials and provider secrets are forbidden here.';

CREATE TABLE v3_source.source_rights_policy (
    rights_policy_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id smallint NOT NULL REFERENCES v3_source.source(source_id),
    policy_version text NOT NULL,
    rights_class text NOT NULL CHECK (rights_class IN (
        'PRIVATE_ONLY', 'INTERNAL_USE', 'SHAREABLE', 'CANONICAL_ELIGIBLE', 'QUARANTINED'
    )),
    retention_class text NOT NULL,
    distribution_allowed boolean NOT NULL DEFAULT false,
    policy_document_uri text,
    policy_sha256 bytea,
    effective_at timestamptz NOT NULL,
    retired_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    UNIQUE (source_id, policy_version),
    UNIQUE (rights_policy_id, source_id),
    CHECK (policy_sha256 IS NULL OR octet_length(policy_sha256) = 32),
    CHECK (retired_at IS NULL OR retired_at >= effective_at)
);

CREATE INDEX source_rights_policy_source_idx
    ON v3_source.source_rights_policy(source_id, effective_at DESC);
COMMENT ON INDEX v3_source.source_rights_policy_source_idx IS 'Use: resolve the effective rights policy for one source acquisition.';

CREATE TABLE v3_source.source_artifact (
    artifact_id uuid PRIMARY KEY,
    source_id smallint NOT NULL REFERENCES v3_source.source(source_id),
    rights_policy_id bigint NOT NULL,
    artifact_kind text NOT NULL,
    endpoint_identity text,
    content_sha256 bytea NOT NULL,
    size_bytes bigint NOT NULL CHECK (size_bytes >= 0),
    media_type text NOT NULL,
    compression_code text,
    retrieved_at timestamptz NOT NULL,
    effective_at timestamptz,
    served_contract_sha256 bytea,
    served_contract_media_type text,
    retention_class text NOT NULL,
    quarantine_state text NOT NULL DEFAULT 'ADMITTED' CHECK (quarantine_state IN (
        'ADMITTED', 'QUARANTINED', 'REJECTED', 'WITHDRAWN'
    )),
    storage_locator text,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    UNIQUE (source_id, content_sha256),
    UNIQUE (artifact_id, source_id),
    FOREIGN KEY (rights_policy_id, source_id)
        REFERENCES v3_source.source_rights_policy(rights_policy_id, source_id),
    CHECK (octet_length(content_sha256) = 32),
    CHECK (served_contract_sha256 IS NULL OR octet_length(served_contract_sha256) = 32)
);

COMMENT ON TABLE v3_source.source_artifact IS 'Immutable acquisition artifact identity and served-contract hash; locators must not contain credentials.';
CREATE INDEX source_artifact_source_retrieved_idx
    ON v3_source.source_artifact(source_id, retrieved_at DESC);
COMMENT ON INDEX v3_source.source_artifact_source_retrieved_idx IS 'Use: list recent immutable artifacts for a source.';

CREATE TABLE v3_source.source_run (
    source_run_id uuid PRIMARY KEY,
    source_id smallint NOT NULL REFERENCES v3_source.source(source_id),
    rights_policy_id bigint NOT NULL,
    artifact_id uuid,
    retry_of_source_run_id uuid,
    acquisition_kind text NOT NULL CHECK (acquisition_kind IN (
        'BULK_SNAPSHOT', 'DELTA', 'STREAM_WINDOW', 'JOURNAL_IMPORT',
        'GOVERNED_RELEASE', 'OPERATOR_ADJUDICATION'
    )),
    trust_zone text NOT NULL CHECK (trust_zone IN ('PRIVATE', 'SHARED', 'CANONICAL')),
    run_state text NOT NULL CHECK (run_state IN (
        'PLANNED', 'RUNNING', 'SUCCEEDED', 'PARTIAL', 'FAILED', 'QUARANTINED', 'CANCELLED'
    )),
    idempotency_key text NOT NULL,
    coverage_domain text,
    scope_contract jsonb NOT NULL DEFAULT '{}'::jsonb,
    is_complete_snapshot boolean NOT NULL DEFAULT false,
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    effective_at timestamptz,
    importer_version text NOT NULL,
    importer_code_sha256 bytea NOT NULL,
    importer_config_sha256 bytea NOT NULL,
    normalizer_version text NOT NULL,
    normalizer_sha256 bytea NOT NULL,
    served_contract_sha256 bytea,
    failure_code text,
    failure_detail text,
    created_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    UNIQUE (source_id, idempotency_key),
    UNIQUE (source_run_id, source_id),
    FOREIGN KEY (rights_policy_id, source_id)
        REFERENCES v3_source.source_rights_policy(rights_policy_id, source_id),
    FOREIGN KEY (artifact_id, source_id)
        REFERENCES v3_source.source_artifact(artifact_id, source_id),
    FOREIGN KEY (retry_of_source_run_id, source_id)
        REFERENCES v3_source.source_run(source_run_id, source_id),
    CHECK (jsonb_typeof(scope_contract) = 'object'),
    CHECK (completed_at IS NULL OR completed_at >= started_at),
    CHECK (octet_length(importer_code_sha256) = 32),
    CHECK (octet_length(importer_config_sha256) = 32),
    CHECK (octet_length(normalizer_sha256) = 32),
    CHECK (served_contract_sha256 IS NULL OR octet_length(served_contract_sha256) = 32),
    CHECK ((run_state IN ('SUCCEEDED', 'PARTIAL', 'FAILED', 'QUARANTINED', 'CANCELLED')) = (completed_at IS NOT NULL))
);

CREATE INDEX source_run_source_started_idx
    ON v3_source.source_run(source_id, started_at DESC);
COMMENT ON INDEX v3_source.source_run_source_started_idx IS 'Use: source acquisition history and latest complete-snapshot reconciliation.';

CREATE TABLE v3_source.source_checkpoint (
    source_run_id uuid NOT NULL REFERENCES v3_source.source_run(source_run_id),
    chunk_key text NOT NULL,
    chunk_ordinal integer NOT NULL CHECK (chunk_ordinal >= 0),
    deterministic_identity_sha256 bytea NOT NULL,
    checkpoint_state text NOT NULL CHECK (checkpoint_state IN (
        'PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED', 'QUARANTINED'
    )),
    input_offset bigint,
    rows_read bigint NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
    rows_accepted bigint NOT NULL DEFAULT 0 CHECK (rows_accepted >= 0),
    rows_rejected bigint NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
    started_at timestamptz,
    completed_at timestamptz,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (source_run_id, chunk_key),
    UNIQUE (source_run_id, chunk_ordinal),
    UNIQUE (source_run_id, deterministic_identity_sha256),
    CHECK (octet_length(deterministic_identity_sha256) = 32),
    CHECK (jsonb_typeof(detail) = 'object'),
    CHECK (completed_at IS NULL OR started_at IS NULL OR completed_at >= started_at)
);

CREATE TABLE v3_source.source_rejection (
    source_rejection_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id uuid NOT NULL,
    chunk_key text,
    rejection_code text NOT NULL,
    entity_kind text,
    source_record_identity text,
    raw_payload_sha256 bytea,
    evidence_locator text,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    rejected_at timestamptz NOT NULL DEFAULT transaction_timestamp(),
    FOREIGN KEY (source_run_id) REFERENCES v3_source.source_run(source_run_id),
    FOREIGN KEY (source_run_id, chunk_key)
        REFERENCES v3_source.source_checkpoint(source_run_id, chunk_key),
    CHECK (raw_payload_sha256 IS NULL OR octet_length(raw_payload_sha256) = 32),
    CHECK (jsonb_typeof(detail) = 'object')
);

CREATE INDEX source_rejection_run_idx
    ON v3_source.source_rejection(source_run_id, rejected_at);
COMMENT ON INDEX v3_source.source_rejection_run_idx IS 'Use: review every rejected record for one acquisition attempt.';

CREATE TABLE v3_source.unmapped_vocabulary (
    unmapped_vocabulary_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_run_id uuid NOT NULL REFERENCES v3_source.source_run(source_run_id),
    vocabulary_domain text NOT NULL,
    raw_token text NOT NULL,
    normalized_candidate text,
    mapping_state text NOT NULL DEFAULT 'UNMAPPED' CHECK (mapping_state IN (
        'UNMAPPED', 'MAPPED', 'QUARANTINED', 'REJECTED'
    )),
    mapped_public_code text,
    first_observed_at timestamptz NOT NULL,
    detail jsonb NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (source_run_id, vocabulary_domain, raw_token),
    CHECK (jsonb_typeof(detail) = 'object'),
    CHECK ((mapping_state = 'MAPPED') = (mapped_public_code IS NOT NULL))
);

