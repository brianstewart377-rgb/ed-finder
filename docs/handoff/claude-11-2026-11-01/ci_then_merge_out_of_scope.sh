#!/bin/bash
# For an Octopus-out-of-scope PR: wait for CI + Codex on HEAD; if every check is green, Codex has no
# unresolved findings, there are no inline review comments on HEAD, and the branch is up to date,
# re-verify scope from the PR file list, post the acceptance record and squash-merge. Otherwise report.
R=repos/brianstewart377-rgb/ed-finder; PR=$1; H=$2; TITLE=$3; S=$(dirname "$0")
bash $S/wait_head.sh $PR $H >/tmp/ci_then_merge_$PR.log 2>&1
bad=$(gh api --paginate "$R/commits/$H/check-runs?per_page=100" --jq '.check_runs[]|select(.name!="Octopus Review" and .conclusion!="success" and .conclusion!="skipped" and .conclusion!="neutral")|"\(.name)=\(.conclusion)"')
cx=$(gh api --paginate "$R/issues/$PR/comments?per_page=100" --jq '[.[]|select(.user.login=="chatgpt-codex-connector[bot]")|.body|capture("codex-review-state:v1 (?<j>\\{.*\\}) -->").j|fromjson|.code_review|"\(.commit_sha) \(.has_unresolved_findings)"]|last')
inline=$(gh api --paginate "$R/pulls/$PR/comments?per_page=100" --jq '[.[]|select(.user.login!="brianstewart377-rgb" and .original_commit_id=="'$H'")]|length')
open_threads=$(gh api "$R/pulls/$PR/ccr/review_threads" --jq '[.[]|select(.resolved!=true)]|length')
behind=$(gh api "$R/compare/main...$H" --jq .behind_by)
head_now=$(gh api "$R/pulls/$PR" --jq .head.sha)
files=$(gh api --paginate "$R/pulls/$PR/files?per_page=100" --jq '.[].filename')
inscope=$(echo "$files" | grep -v '\.md$' | grep -E '^(sql/|\.github/workflows/|deploy/|scripts/operator/|scripts/rehearsal/|apps/api/src/auth\.py$|apps/api/src/routers/auth\.py$|apps/web/src/lib/auth/|apps/api/src/edfinder_api/journal/)' ; echo "$files" | grep -v '\.md$' | grep -v '^docs/' | grep -i purge)
echo "nonsuccess=[$bad] codex=[$cx] inline=$inline open_threads=$open_threads behind=$behind head_now=$head_now inscope=[$inscope]"
if [ -n "$bad" ] || [ "$cx" != "$H false" ] || [ "$inline" != 0 ] || [ "$open_threads" != 0 ] || [ "$behind" != 0 ] || [ "$head_now" != "$H" ] || [ -n "$inscope" ]; then echo "NOT MERGING"; exit 0; fi
list=$(echo "$files" | sed 's/^/- `/; s/$/`/')
gh api -X POST $R/issues/$PR/comments -f body="**Merge acceptance — head \`${H:0:8}\`**

- Protected CI: all green on this exact head (the Octopus Review check is the neutral auto-skip).
- Codex Review: completed on \`${H:0:10}\`, no unresolved findings; no inline review comments; no open review threads.
- **Octopus scope:** out of scope under the owner decision of 2026-10-31. Changed files:
$list
  None matches a scope rule.
- Branch up to date with \`main\`.

---
_Generated by [Claude Code](https://claude.ai/code)_" --jq .html_url
gh api -X PUT $R/pulls/$PR/merge -f sha=$H -f merge_method=squash -f commit_title="$TITLE (#$PR)" --jq '"MERGED \(.merged) \(.sha)"'
