#!/bin/bash
# Wait for CI + Codex on PR head; if green and Codex clean and up to date, request Octopus and wait for its review or refusal.
R=repos/brianstewart377-rgb/ed-finder; PR=$1; H=$2; S=$(dirname "$0")
bash $S/wait_head.sh $PR $H >/tmp/ci_then_octopus_$PR.log 2>&1
bad=$(gh api --paginate "$R/commits/$H/check-runs?per_page=100" --jq '.check_runs[]|select(.name!="Octopus Review" and .conclusion!="success" and .conclusion!="skipped" and .conclusion!="neutral")|.name')
cx=$(gh api --paginate "$R/issues/$PR/comments?per_page=100" --jq '[.[]|select(.user.login=="chatgpt-codex-connector[bot]")|.body|capture("codex-review-state:v1 (?<j>\\{.*\\}) -->").j|fromjson|.code_review|"\(.commit_sha) \(.has_unresolved_findings)"]|last')
behind=$(gh api "$R/compare/main...$H" --jq .behind_by)
echo "nonsuccess=[$bad] codex=[$cx] behind=$behind"
if [ -n "$bad" ] || [ "$cx" != "$H false" ] || [ "$behind" != 0 ]; then echo "NOT REQUESTING OCTOPUS"; exit 0; fi
SINCE=$(date -u +%Y-%m-%dT%H:%M:%SZ)
gh api -X POST $R/issues/$PR/comments -f body="@octopus-review

Final merge candidate: head \`${H:0:8}\` (in Octopus scope). CI green and Codex clean on this exact head; branch up to date with \`main\`.

---
_Generated by [Claude Code](https://claude.ai/code)_" --jq .html_url
for i in $(seq 1 120); do
  r=$(gh api --paginate "$R/pulls/$PR/reviews?per_page=100" --jq '[.[]|select((.user.login|test("octopus";"i")) and .commit_id=="'$H'" and .submitted_at>"'$SINCE'")]|length')
  [ "${r:-0}" -gt 0 ] && { sleep 20; echo "REVIEW POSTED"; break; }
  ref=$(gh api --paginate "$R/issues/$PR/comments?per_page=100" --jq '[.[]|select((.user.login|test("octopus";"i")) and .updated_at>"'$SINCE'" and (.body|test("out of credits|spend limit";"i")))]|length')
  [ "${ref:-0}" -gt 0 ] && { echo "REFUSED"; break; }
  sleep 30
done
gh api --paginate "$R/issues/$PR/comments?per_page=100" --jq '.[]|select((.user.login|test("octopus";"i")) and .updated_at>"'$SINCE'")|"COMMENT \(.updated_at)\n\(.body)"'
gh api --paginate "$R/pulls/$PR/reviews?per_page=100" --jq '.[]|select((.user.login|test("octopus";"i")) and .submitted_at>"'$SINCE'")|"REVIEW \(.state) \(.commit_id[0:8])\n\(.body)"'
gh api --paginate "$R/pulls/$PR/comments?per_page=100" --jq '.[]|select((.user.login|test("octopus";"i")) and .created_at>"'$SINCE'")|"INLINE id=\(.id) \(.path):\(.line)\n\(.body)"'
