#!/usr/bin/env python3
"""Measure Search storage on three fresh, disposable PostgreSQL 18 databases.

The rows are generated by this program because a disposable database has no
canonical Search source.  ``declared-synthetic-text-v1`` uses seed 20261010 and
independently selects realistic UTF-8/ASCII lengths: names are 6--64 bytes
(weighted toward 8--24), region names are NULL 8% of the time and otherwise
6--64 bytes (weighted toward 10--32), and main-star classes are NULL 3% of the
time and otherwise 1--12 bytes (weighted toward 1--3).  Characters come from a
declared ASCII alphabet, so character and octet lengths agree.  The fixed run
uses exactly one byte in each of the three text columns.

The pre-010, post-010, and fixed measurements each start from an empty, newly
created database and fill identical non-text values.  This is essential:
PostgreSQL's fast defaults would make sizing a populated table before and after
``ALTER TABLE`` report almost none of the bytes that newly inserted rows store.

Safety: ``EDFINDER_DISPOSABLE_DSN`` is the only connection source.  It must
name the allowlisted validation database on loopback, ambient libpq routing is
refused, and the connected server is verified as PostgreSQL 18 before the
first write.  Every measurement database has a random ``search_measure_`` name
and is force-dropped in ``finally``.  No canonical or production database is
read.
"""

