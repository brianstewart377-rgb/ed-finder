def port_cp_cost(tier: int, counted_port_number: int) -> tuple[int, int]:
    """Return (yellow, green) for a tier at the shared 1-based port count.

    The count includes all paid escalating T2 and T3 ports, regardless of tier.
    Callers exclude primary ports and non-escalating facilities from this count.
    Mega Guide v2.3.0 PDF p27-28; CRE CL-0013..CL-0024, CR-0010..CR-0012.
    """
    if tier == 3:
        return 0, t3_port_green_cost(counted_port_number)
    if tier == 2:
        return t2_port_yellow_cost(counted_port_number), 0
    return 0, 0


class _DummyFacility:
    """Minimal facility-like object for cost simulation."""
    def __init__(self, tier: int):
        self.tier       = tier
        self.id         = f'_sim_t{tier}'
        self.is_port    = True
        self.yellow_cp_cost = 0
        self.green_cp_cost  = 0

def _dummy_t2_port() -> '_DummyFacility':
    return _DummyFacility(2)

def _dummy_t3_port() -> '_DummyFacility':
    return _DummyFacility(3)
